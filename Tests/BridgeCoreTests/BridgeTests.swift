@Test
func screenshotMetadataWorksRegardlessOfFilename() throws {
    let file = FileManager.default.temporaryDirectory.appendingPathComponent("localized-\(UUID()).png")
    try Data().write(to: file)
    defer { try? FileManager.default.removeItem(at: file) }
    #expect(!ScreenshotFiles.isScreenshot(file))
    let metadata = try PropertyListSerialization.data(fromPropertyList: "true", format: .binary, options: 0)
    let result = metadata.withUnsafeBytes { bytes in
        setxattr(file.path, "com.apple.metadata:kMDItemIsScreenCapture", bytes.baseAddress, metadata.count, 0, 0)
    }
    #expect(result == 0)
    #expect(ScreenshotFiles.isScreenshot(file))
}

private func markScreenshot(_ file: URL) throws {
    let metadata = try PropertyListSerialization.data(fromPropertyList: "true", format: .binary, options: 0)
    let result = metadata.withUnsafeBytes { bytes in
        setxattr(file.path, "com.apple.metadata:kMDItemIsScreenCapture", bytes.baseAddress, metadata.count, 0, 0)
    }
    #expect(result == 0)
}

@Test @MainActor
func folderWatcherCopiesOnlyNewScreenshots() throws {
    try withBridge { bridge, folder in
        let old = folder.appendingPathComponent("old.png")
        try fixture().write(to: old)
        try markScreenshot(old)
        let watcher = ScreenshotWatcher(bridge: bridge)
        defer { watcher.pause() }
        watcher.watch(folder)
        let ordinary = folder.appendingPathComponent("ordinary.png")
        try fixture().write(to: ordinary)
        let screenshot = folder.appendingPathComponent("localized screenshot.png")
        try fixture().write(to: screenshot)
        try markScreenshot(screenshot)
        watcher.tick()
        #expect(bridge.lastFile?.resolvingSymlinksInPath() == screenshot.resolvingSymlinksInPath())
        let pastedFile = try #require(bridge.pasteboard.string(forType: .fileURL).flatMap(URL.init(string:)))
        #expect(pastedFile.resolvingSymlinksInPath() == screenshot.resolvingSymlinksInPath())
    }
}

@Test @MainActor
func delayedMetadataDoesNotReplaceNewCopy() throws {
    try withBridge { bridge, folder in
        let watcher = ScreenshotWatcher(bridge: bridge)
        defer { watcher.pause() }
        watcher.watch(folder)
        let screenshot = folder.appendingPathComponent("new.png")
        try fixture().write(to: screenshot)
        watcher.tick()
        bridge.pasteboard.clearContents()
        bridge.pasteboard.setString("copied during screenshot write", forType: .string)
        try markScreenshot(screenshot)
        watcher.tick()
        #expect(bridge.lastFile == nil)
        #expect(bridge.pasteboard.string(forType: .string) == "copied during screenshot write")
    }
}

