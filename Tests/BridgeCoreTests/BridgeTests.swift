@MainActor
private func fixture() throws -> Data {
    let bitmap = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 8, pixelsHigh: 6,
        bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
        colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
    let blue = NSColor(deviceRed: 0.15, green: 0.45, blue: 0.9, alpha: 1)
    for x in 0..<8 { for y in 0..<6 { bitmap.setColor(blue, atX: x, y: y) } }
    return try #require(bitmap.representation(using: .png, properties: [:]))
}

@MainActor
private func withBridge(_ body: (ClipboardBridge, URL) throws -> Void) throws {
    let folder = FileManager.default.temporaryDirectory.resolvingSymlinksInPath().appendingPathComponent("BridgeTests-\(UUID())")
    try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
    let pasteboard = NSPasteboard.withUniqueName()
    let bridge = ClipboardBridge(pasteboard: pasteboard, saveDirectory: folder)
    defer { pasteboard.releaseGlobally(); try? FileManager.default.removeItem(at: folder) }
    try body(bridge, folder)
}

@MainActor
private func copyImage(_ data: Data, to pasteboard: NSPasteboard, extraType: NSPasteboard.PasteboardType? = nil) {
    let item = NSPasteboardItem()
    item.setData(data, forType: .png)
    if let extraType { item.setString("existing", forType: extraType) }
    pasteboard.clearContents()
    pasteboard.writeObjects([item])
}

@Test @MainActor
func clipboardImageBecomesRealFileAndThreeReadableRepresentations() throws {
    try withBridge { bridge, _ in
        let png = try fixture()
        copyImage(png, to: bridge.pasteboard)
        let file = try #require(try bridge.processClipboardIfChanged())
        #expect(try Data(contentsOf: file) == png)
        #expect(bridge.pasteboard.data(forType: .png) == png)
        #expect(bridge.pasteboard.string(forType: .string) == file.path)
        #expect(bridge.pasteboard.string(forType: .fileURL) == file.absoluteString)
        let image = try #require(NSImage(pasteboard: bridge.pasteboard))
        #expect(image.size.width == 8 && image.size.height == 6)
        let urls = try #require(bridge.pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]))
        #expect((urls.first as? URL) == file)
        #expect(bridge.pasteboard.pasteboardItems?.count == 1)
    }
}

@Test @MainActor
func selfPublicationDoesNotLoopOrDuplicateFiles() throws {
    try withBridge { bridge, folder in
        copyImage(try fixture(), to: bridge.pasteboard)
