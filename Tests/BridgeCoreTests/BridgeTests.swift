@Test @MainActor
func newestSavedScreenshotWinsWhenFilesArriveTogether() throws {
    try withBridge { bridge, folder in
        let watcher = ScreenshotWatcher(bridge: bridge)
        defer { watcher.pause() }
        watcher.watch(folder)
        let first = folder.appendingPathComponent("first.png")
        let last = folder.appendingPathComponent("last.png")
        for (file, offset) in [(first, 1.0), (last, 2.0)] {
            try fixture().write(to: file)
            try markScreenshot(file)
            try FileManager.default.setAttributes([.creationDate: Date().addingTimeInterval(offset)], ofItemAtPath: file.path)
        }
        watcher.tick()
        #expect(bridge.lastFile?.resolvingSymlinksInPath() == last.resolvingSymlinksInPath())
    }
}
